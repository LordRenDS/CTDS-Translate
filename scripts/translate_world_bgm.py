def apply_translations(rel_path, translation_map):
    p = AI_MSG_DIR / rel_path
    with open(p, "r", encoding="utf-8") as f:
        data = json.load(f)

    for item in data:
        idx = item["id"]
        orig = item.get("original_en", "")
        if orig.strip():
            if idx in translation_map:
                item["translation"] = translation_map[idx]
            else:
                print(f"Warning: missing translation for {rel_path} ID {idx}: {orig!r}")

    with open(p, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Updated {rel_path}")


def fix_zukan():
    p = AI_MSG_DIR / "big/zukan.json"
    with open(p, "r", encoding="utf-8") as f:
        data = json.load(f)
    for item in data:
        if not item.get("translation") and item.get("original_en"):
            item["translation"] = item["original_en"]
    with open(p, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print("Updated big/zukan.json")


