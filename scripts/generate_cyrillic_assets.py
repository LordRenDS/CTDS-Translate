def build_cyrillic_sheet(
    cell_w: int,
    cell_h: int,
    patterns: Dict[str, List[str]],
    output_png: str,
    output_json: str,
) -> None:
    """Builds a PNG glyph sheet and JSON descriptor for Cyrillic characters."""
    cols = 16
    glyph_count = len(ALL_CYRILLIC_CHARS)
    rows = (glyph_count + cols - 1) // cols

    img_w = cols * cell_w
    img_h = rows * cell_h

    img = Image.new("P", (img_w, img_h), 0)
    img.putpalette(PALETTE_2BPP)

    glyphs_meta = []

    for i, char in enumerate(ALL_CYRILLIC_CHARS):
        gx = i % cols
        gy = i // cols
        cx = gx * cell_w
        cy = gy * cell_h

        body_lines = patterns.get(char, [""] * cell_h)
        glyph_w, grid = _apply_shadow(body_lines, cell_w, cell_h)

        # Place glyph pixels
        for y in range(cell_h):
            for x in range(cell_w):
                val = grid[y][x]
                if val > 0:
                    img.putpixel((cx + x, cy + y), val)

        bpr = (glyph_w + 3) // 4
        font_glyph_id = 450 + i

        glyphs_meta.append({
            "index": i,
            "font_glyph_id": font_glyph_id,
            "char": char,
            "width": glyph_w,
            "bpr": bpr,
            "grid_x": gx,
            "grid_y": gy,
        })

    # Apply cell boundaries (color 4)
    v_lines = [0] + [(gx + 1) * cell_w - 1 for gx in range(cols)]
    for vx in v_lines:
        if vx < img_w:
            for y in range(img_h):
                if img.getpixel((vx, y)) == 0:
                    img.putpixel((vx, y), GRID_COLOR_CELL)

    h_lines = [0] + [(gy + 1) * cell_h - 1 for gy in range(rows)]
    for hy in h_lines:
        if hy < img_h:
            for x in range(img_w):
                if img.getpixel((x, hy)) == 0:
                    img.putpixel((x, hy), GRID_COLOR_CELL)

    # Apply glyph width boundary markers (color 5)
    for g in glyphs_meta:
        w = g["width"]
        if 0 < w < cell_w:
            cx = g["grid_x"] * cell_w
            cy = g["grid_y"] * cell_h
            wx = cx + w
            if wx < img_w:
                for y in range(cy, cy + cell_h):
                    if img.getpixel((wx, y)) not in (1, 2, 3):
                        img.putpixel((wx, y), GRID_COLOR_WIDTH)

    os.makedirs(os.path.dirname(os.path.abspath(output_png)), exist_ok=True)
    img.save(output_png)

    meta = {
        "magic": "CYRFONT",
        "cell_width": cell_w,
        "cell_height": cell_h,
        "grid_columns": cols,
        "grid_rows": rows,
        "glyph_count": glyph_count,
        "glyphs": glyphs_meta,
    }

    os.makedirs(os.path.dirname(os.path.abspath(output_json)), exist_ok=True)
    with open(output_json, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)

    print(f"Generated {output_png} ({img_w}x{img_h}) and {output_json} with {glyph_count} glyphs.")


def main():
    assets_dir = os.path.join("assets", "fonts")
    os.makedirs(assets_dir, exist_ok=True)

    small_png = os.path.join(assets_dir, "cyrillic_small.png")
    small_json = os.path.join(assets_dir, "cyrillic_small.json")
    build_cyrillic_sheet(8, 8, SMALL_PATTERNS, small_png, small_json)

    big_png = os.path.join(assets_dir, "cyrillic_big.png")
    big_json = os.path.join(assets_dir, "cyrillic_big.json")
    build_cyrillic_sheet(12, 10, BIG_PATTERNS, big_png, big_json)


if __name__ == "__main__":
    main()
