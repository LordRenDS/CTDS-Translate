from PIL import Image

PALETTE_2BPP = [
    0, 0, 0,        # 0: Transparent/Black
    255, 255, 255,  # 1: Font body (white)
    180, 180, 180,  # 2: Anti-alias (light gray)
    90, 90, 90,     # 3: Shadow (dark gray)
    50, 80, 140,    # 4: Cell border grid
    180, 70, 50,    # 5: Glyph width boundary
] + [0] * (256 * 3 - 18)

GRID_COLOR_CELL = 4
GRID_COLOR_WIDTH = 5

CYRILLIC_UPPER = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"  # 32 chars: 0x80..0x9F -> glyphs 450..481
CYRILLIC_LOWER = "абвгдежзийклмнопрстуфхцчшщъыьэюя"  # 32 chars: 0xA0..0xBF -> glyphs 482..513
CYRILLIC_SPECIAL = [("Ё", 0xC0), ("ё", 0xC1)]          # 2 chars: 0xC0, 0xC1 -> glyphs 514, 515

ALL_CYRILLIC_CHARS: List[str] = list(CYRILLIC_UPPER) + list(CYRILLIC_LOWER) + [c for c, _ in CYRILLIC_SPECIAL]


def _apply_shadow(body_lines: List[str], cell_w: int, cell_h: int) -> Tuple[int, List[List[int]]]:
    """Applies CTDS 2bpp drop shadow (+1,0), (0,+1), (+1,+1) to a 1-bit glyph body."""
    padded = body_lines + [""] * (cell_h - len(body_lines))
    padded = padded[:cell_h]

    # Determine body width
    max_body_x = 0
    has_pixels = False
    for y in range(cell_h):
        line = padded[y]
        for x in range(len(line)):
            if line[x] == "#":
                max_body_x = max(max_body_x, x)
                has_pixels = True

    # Glyph width includes body plus 1px right shadow
    glyph_w = min(cell_w, max_body_x + 2 if has_pixels else 3)

    grid = [[0] * cell_w for _ in range(cell_h)]
    for y in range(cell_h):
        line = padded[y]
        for x in range(min(cell_w, len(line))):
            if line[x] == "#":
                grid[y][x] = 1

    # Add drop shadow
    for y in range(cell_h):
        for x in range(cell_w):
            if grid[y][x] == 1:
                for dy, dx in [(0, 1), (1, 0), (1, 1)]:
                    ny, nx = y + dy, x + dx
                    if 0 <= ny < cell_h and 0 <= nx < cell_w and grid[ny][nx] == 0:
                        grid[ny][nx] = 3

    return glyph_w, grid


