"""Generates pixel-perfect Cyrillic font templates (PNG + JSON) for Chrono Trigger DS.

Creates:
  - assets/fonts/cyrillic_small.png and assets/fonts/cyrillic_small.json (8x8 cells)
  - assets/fonts/cyrillic_big.png and assets/fonts/cyrillic_big.json (12x10 cells)
"""

import json
